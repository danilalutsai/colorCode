// Creating a new object with brackets is called object literal
// Is the simpliest way to create an empty object
const dude = {}

console.log(dude) // {} -> __proto__:Object

dude.name = 'Danila'
dude.age = 28

dude.talk // undefined
dude.speak // undefined
dude.string // methods built in Object
dude.valueOf // methods built in Object
